def sec_statistics(manifest: dict, integ: dict) -> str:
    n = manifest["n_seeds"]
    mde80 = S.minimum_detectable_effect(n, 0.80)
    mde90 = S.minimum_detectable_effect(n, 0.90)
    fam = integ["family"] if integ else None
    n_comp = fam["n_comparisons"] if fam else 0
    thr = fam["bonferroni_threshold"] if fam else float("nan")

    best = None
    if fam:
        best = max(fam["rows"], key=lambda r: abs(r["cohens_d"]))

    norm_lines = []
    if integ:
        for m, v in integ["normality"].items():
            verdict = ("consistent with normality" if v["normal_at_005"]
                       else "NOT consistent with normality")
            norm_lines.append(f"| `{m}` | {f(v['W'], 3)} | {pfmt(v['p'])} | {verdict} |")

    n_mc = manifest["n_monte_carlo_per_seed"]
    return f"""## 1. Statistical methodology (Section 8.2 of the article)

### 1.1 The sample-size correction demanded by Reviewer 1, comment 6

The previous draft stated that the effective sample size was
`N_seeds x N_MONTE_CARLO = 5 x 1000 = 5000 realizations per load point`.
**That statement is wrong and has been removed.** The Monte Carlo iterations inside a
seed are averaged into a single per-seed estimate before any inference is performed;
averaging reduces the variance of that estimate but produces no additional independent
observations. The independent sample size equals the number of seeds.

This campaign therefore uses **{n} independent seeds**, and every confidence interval
and every test below carries **df = {n} - 1 = {n - 1}**. The code enforces the rule:
`stats.describe()` stores `n_monte_carlo_per_seed` as a separate, inference-inert
field, and `tests/test_stats.py::test_degrees_of_freedom_are_seeds_minus_one_not_iterations`
fails if that field is ever allowed to change a confidence interval.

**Recommended replacement wording for the article (Section 8.2):**

> Results are reported as the mean over {n} independent random seeds, with 95 %
> confidence intervals computed from Student's t distribution with {n - 1} degrees of
> freedom. Each seed averages {manifest['n_monte_carlo_per_seed']} Monte Carlo
> iterations into a single estimate; this averaging reduces the variance of each seed's
> estimate but does not increase the number of independent observations, so the
> effective sample size is {n} and not {n} x {manifest['n_monte_carlo_per_seed']}.

### 1.2 Design

* **Common random numbers.** The same seed list drives every arm of every experiment,
  so all comparisons are **paired** at the seed level. Within an experiment, the
  channel and traffic realisations replayed for each arm are identical; the arms differ
  only in the control policy.
* **Paired t-test** on the seed-wise difference vector, two-sided.
* **Wilcoxon signed-rank test** on the same vector as a distribution-free robustness
  check, since n = {n} is modest.
* **Cohen's d_z** = mean difference / SD of the differences, with Cohen's (1988)
  conventional bands (negligible < 0.2, small < 0.5, medium < 0.8, large < 1.2).
* **Bonferroni** correction within each declared family of comparisons, and
  **Holm-Bonferroni** reported alongside it as the uniformly more powerful alternative
  controlling the same family-wise error rate.
* **Shapiro-Wilk** on the paired differences, so the reader can judge how much weight
  to give the t-test relative to the Wilcoxon result.
* **Bounded metrics.** Several reported quantities are probabilities or fractions.
  The Student-t interval is symmetric and is NOT truncated at the natural bounds, so a
  near-zero probability can be reported with a negative lower limit. Those limits are
  left as the arithmetic produces them rather than being quietly clipped; when such a
  number is quoted in the article the lower limit should be read as zero and the
  interval described as one-sided in effect. Where the metric is strongly skewed the
  Wilcoxon result, which makes no symmetry assumption, is the one to rely on.

### 1.3 Power

At n = {n} seeds and alpha = 0.05 two-sided, the **minimum detectable effect** is

* d_z = **{f(mde80, 3)}** at 80 % power,
* d_z = **{f(mde90, 3)}** at 90 % power.

Effects smaller than these cannot be reliably detected by this design, and the article
must not claim them.

**Caution on very large effect sizes.** Cohen's `d_z` is the mean difference divided by
the standard deviation of the *between-seed* differences. Because each seed averages
{n_mc} Monte Carlo iterations, the between-seed variance of a well-behaved quantity is
very small, so `d_z` can reach values in the tens or hundreds. Such a number means the
difference is extremely consistent across replications; it does **not** mean the
difference is large in engineering terms. The article should therefore quote the
absolute difference and its confidence interval first, and the effect size second.

{'The largest effect in the integrated end-to-end family is `' + best['metric'] + '`, '
 + SHORT_ARM.get(best['arm_a'], best['arm_a']) + ' vs ' + SHORT_ARM.get(best['arm_b'], best['arm_b'])
 + ', with d_z = ' + f(best['cohens_d'], 2) + ' and achieved power '
 + f(best['achieved_power'], 3) + '.' if best else ''}

### 1.4 Normality of the paired differences (E vs A)

{table(['Metric', 'Shapiro-Wilk W', 'p', 'Verdict'], []) if not norm_lines else
 '| Metric | Shapiro-Wilk W | p | Verdict |' + chr(10) + '|---|---|---|---|' + chr(10) + chr(10).join(norm_lines)}

### 1.5 Families and corrected thresholds

The integrated end-to-end family contains **{n_comp}** comparisons, so the
Bonferroni-adjusted per-comparison threshold is **alpha = {pfmt(thr)}** against a
family-wise alpha of 0.05. Every other experiment declares its own family; the
threshold used is printed in that experiment's table.

---
"""


