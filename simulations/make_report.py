def sec_summary(blobs: dict, manifest: dict) -> str:
    integ = blobs.get("integrated")
    learn = blobs.get("learners")
    lines = [
        "| Reviewer comment | Where it is addressed | Status |",
        "|---|---|---|",
        "| R1.1 UMRO-5G not evaluated as an integrated framework | Section 3 (integrated end-to-end runner, five arms, measured loop coupling, Figure 4) | addressed with new original data |",
        "| R1.2 DRL results come from proxy agents | Section 4 (four real agents in NumPy, gradient-checked; proxies deleted) | addressed; non-convergence reported honestly where measured |",
        "| R1.5 statistical analysis mentioned but not presented | Sections 1, 3.6, 4.5, 5.3, 6.1, 8.5, 9.4 (CIs, t and Wilcoxon tests, p-values, Bonferroni and Holm thresholds, effect sizes, power) | addressed |",
        "| R1.6 effective sample size | Section 1.1 (rule stated, enforced in code, unit-tested) | addressed; the 5000-sample claim is deleted |",
        "| R1.8 Figures 3 and 4 have no methodology | Sections 8 and 9 (full models, assumptions, baselines, uncertainty) | addressed |",
        "| R1.9 conclusions stronger than the evidence | Section 12 (claim-by-claim replacement wording) | addressed |",
        "| R1.10 repository contents and provenance separation | `simulations/README.md` and the PROVENANCE section | addressed |",
    ]
    unresolved = [
        "",
        "### Unresolved / flagged",
        "",
        "* The O-RU power values (200 W / 20 W / 500 W) are carried over from the "
        "previous draft with no source. They are classified ILLUSTRATIVE in PROVENANCE. "
        "If a source exists it should be cited; otherwise the article must call them "
        "assumed values.",
        "* The medium-loop controller is pre-trained on a fluid surrogate rather than on "
        "the full simulator, for runtime reasons. This is disclosed in Section 3.8 and "
        "in `simulations/README.md` Section 7.",
        "* The RIS results assume perfect CSI and are upper bounds; no estimation "
        "overhead is modelled.",
        f"* The complexity benchmark uses {manifest['n_seeds_complexity']} seeds "
        f"rather than {manifest['n_seeds']} because it must run sequentially; its "
        f"confidence intervals carry df = {manifest['n_seeds_complexity'] - 1} and this "
        f"is stated wherever those numbers appear.",
    ]
    if learn:
        nc = [a for a, v in learn["converged_fraction"].items() if v < 0.5]
        if nc:
            unresolved.append(
                f"* {', '.join(nc)} did not meet the convergence criteria in the "
                f"majority of runs within the {RLTRAIN.n_episodes}-episode budget. This "
                f"is reported as a negative result, not smoothed over.")
    if integ:
        rows = {(r['arm_a'], r['arm_b'], r['metric']): r for r in integ['family']['rows']}
        ns = [r for r in integ['family']['rows'] if not r['significant_bonferroni']]
        if ns:
            unresolved.append(
                f"* {len(ns)} of the {integ['family']['n_comparisons']} comparisons in "
                f"the integrated end-to-end family are NOT significant after Bonferroni "
                f"correction: "
                + "; ".join(f"{r['metric']} ({SHORT_ARM.get(r['arm_a'], r['arm_a'])} vs "
                            f"{SHORT_ARM.get(r['arm_b'], r['arm_b'])})" for r in ns)
                + ". The article must report these as not significant.")
    return "## SUMMARY\n\n" + "\n".join(lines) + "\n" + "\n".join(unresolved) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--out", default="../work/sim_results.md")
    args = ap.parse_args(argv)
    results = Path(args.results)
    manifest = load(results, "run_manifest")
    if manifest is None:
        raise SystemExit(f"no run_manifest.json in {results.resolve()}")

    blobs = {n: load(results, n) for n in
             ("integrated", "learners", "slicing", "scheduling", "sfc", "energy",
              "ris", "complexity")}
    blobs = {k: v for k, v in blobs.items() if v is not None}

    parts = [
        sec_header(manifest),
        sec_statistics(manifest, blobs.get("integrated")),
        sec_scenario_table(),
        sec_integrated(blobs.get("integrated")),
        sec_learners(blobs.get("learners")),
        sec_slicing(blobs.get("slicing")),
        sec_scheduling(blobs.get("scheduling")),
        sec_sfc(blobs.get("sfc")),
        sec_energy(blobs.get("energy")),
        sec_ris(blobs.get("ris")),
        sec_complexity(blobs.get("complexity")),
        sec_consolidated(blobs.get("integrated"), blobs.get("learners"),
                         blobs.get("scheduling"), blobs.get("energy"),
                         blobs.get("ris"), blobs.get("complexity"),
                         blobs.get("sfc")),
        sec_claims(blobs.get("integrated"), blobs.get("learners"),
                   blobs.get("energy"), blobs.get("ris"), blobs.get("complexity")),
        sec_provenance(blobs, manifest),
        sec_summary(blobs, manifest),
    ]
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out.resolve()}  ({len(''.join(parts)):,} characters)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
