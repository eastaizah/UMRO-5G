def f(x, d=3):
    if x is None:
        return "n/a"
    try:
        v = float(x)
    except (TypeError, ValueError):
        return str(x)
    if not np.isfinite(v):
        return "inf" if v > 0 else "-inf"
    return f"{v:.{d}f}"


def fsig(x, d=4):
    """Fixed-point normally, scientific when the value would round to zero."""
    if x is None:
        return "n/a"
    v = float(x)
    if not np.isfinite(v):
        return "inf" if v > 0 else "-inf"
    if v != 0.0 and abs(v) < 0.5 * 10 ** (-d):
        return f"{v:.2e}"
    return f"{v:.{d}f}"


def ci(s: dict, unit: str = "", d: int = 3) -> str:
    """mean (95 % CI [lo, hi])"""
    u = f" {unit}" if unit else ""
    return (f"{f(s['mean'], d)}{u} (95 % CI [{f(s['ci_low'], d)}, "
            f"{f(s['ci_high'], d)}])")


def msd(s: dict, unit: str = "", d: int = 3) -> str:
    u = f" {unit}" if unit else ""
    return (f"{f(s['mean'], d)} +/- {f(s['sd'], d)}{u}; 95 % CI "
            f"[{f(s['ci_low'], d)}, {f(s['ci_high'], d)}]; n = {s['n_seeds']}")


def pfmt(p) -> str:
    p = float(p)
    if p == 0.0:
        return "< 1e-300"
    if p < 1e-4:
        return f"{p:.2e}"
    return f"{p:.4f}"


def table(header: Iterable[str], rows: Iterable[Iterable[str]]) -> str:
    header = list(header)
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join(["---"] * len(header)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(v) for v in r) + " |")
    return "\n".join(out)


def comparison_table(family: dict, d: int = 4, label_map: dict | None = None) -> str:
    label_map = label_map or {}

    def lbl(x):
        return label_map.get(x, x)

    rows = []
    for r in family["rows"]:
        rows.append([
            r["metric"],
            f"{lbl(r['arm_a'])} - {lbl(r['arm_b'])}",
            fsig(r["mean_diff"], d),
            f"[{fsig(r['diff_ci_low'], d)}, {fsig(r['diff_ci_high'], d)}]",
            f(r["t_stat"], 3),
            pfmt(r["p_raw"]),
            pfmt(family["bonferroni_threshold"]),
            f"{f(r['cohens_d'], 2)} ({r['d_interpretation']})",
            "**yes**" if r["significant_bonferroni"] else "no",
            "yes" if r["significant_holm"] else "no",
            pfmt(r["wilcoxon_p"]),
            f(r["achieved_power"], 3),
        ])
    return table(["Metric", "Comparison", "Difference", "95 % CI of the difference",
                  "t", "raw p", "Bonferroni threshold", "Cohen's d",
                  "Significant (Bonferroni)", "Significant (Holm)",
                  "Wilcoxon p", "Achieved power"], rows)


